import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const galleryRoot = path.resolve(__dirname, '..');
const operatorRoot = path.resolve(galleryRoot, '..');
const releaseRoot = path.resolve(operatorRoot, '..');
const releaseStatusPath = path.join(releaseRoot, '00_PUBLIC', 'RELEASE-STATUS.json');
const outputPath = path.join(galleryRoot, 'src', 'generated', 'release', 'releaseCoordinates.ts');

export function deriveReleaseCoordinates() {
  if (!fs.existsSync(releaseStatusPath)) {
    throw new Error(`Authoritative release status missing at ${releaseStatusPath}`);
  }

  const raw = fs.readFileSync(releaseStatusPath, 'utf8');
  let status;
  try {
    status = JSON.parse(raw);
  } catch (err) {
    throw new Error(`Failed to parse RELEASE-STATUS.json: ${err.message}`);
  }

  const publicRepoPublished = Boolean(status?.external_gates?.public_repo_published);
  const publicRepoBaseUrl = 'https://github.com/thienannguyen-cv/hien-sinh-gallery';
  const verifyDocUrl = `${publicRepoBaseUrl}/blob/main/00_PUBLIC/VERIFY.md`;
  const independentOperationDocUrl = `${publicRepoBaseUrl}/blob/main/00_PUBLIC/INDEPENDENT-OPERATION.md`;

  const code = `// @generated by scripts/export-release-coordinates.mjs; do not edit manually.
export interface ReleaseCoordinates {
  readonly publicRepoPublished: boolean;
  readonly publicRepoBaseUrl: string;
  readonly verifyDocUrl: string;
  readonly independentOperationDocUrl: string;
}

export const RELEASE_COORDINATES: ReleaseCoordinates = {
  publicRepoPublished: ${publicRepoPublished},
  publicRepoBaseUrl: ${JSON.stringify(publicRepoBaseUrl)},
  verifyDocUrl: ${JSON.stringify(verifyDocUrl)},
  independentOperationDocUrl: ${JSON.stringify(independentOperationDocUrl)},
} as const;
`;

  return {
    publicRepoPublished,
    publicRepoBaseUrl,
    verifyDocUrl,
    independentOperationDocUrl,
    code,
  };
}

export async function verifyNetworkReachable(coordinates) {
  if (!coordinates.publicRepoPublished) {
    return { ok: true, skipped: true };
  }

  const urls = [
    coordinates.publicRepoBaseUrl,
    coordinates.verifyDocUrl,
    coordinates.independentOperationDocUrl,
  ];

  for (const url of urls) {
    try {
      const res = await fetch(url, { method: 'HEAD' });
      if (!res.ok && res.status !== 405) {
        throw new Error(`URL ${url} returned status ${res.status}`);
      }
    } catch (err) {
      throw new Error(`Live-Go verification failed for ${url}: ${err.message}`);
    }
  }

  return { ok: true, skipped: false };
}

function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes('--check');
  const verifyNetwork = args.includes('--verify-network');

  const derived = deriveReleaseCoordinates();

  if (verifyNetwork) {
    verifyNetworkReachable(derived).then(() => {
      console.log('Network reachability verified for all public evidence routes.');
    }).catch(err => {
      console.error(err.message);
      process.exit(1);
    });
    return;
  }

  if (checkOnly) {
    if (!fs.existsSync(outputPath)) {
      throw new Error(`Generated release coordinates missing at ${outputPath}. Run 'node scripts/export-release-coordinates.mjs'.`);
    }
    const current = fs.readFileSync(outputPath, 'utf8');
    if (current !== derived.code) {
      throw new Error(`Generated release coordinates at ${outputPath} are stale or modified. Run 'node scripts/export-release-coordinates.mjs'.`);
    }
    console.log('Generated release coordinates match authoritative RELEASE-STATUS.json.');
    return;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, derived.code, 'utf8');
  console.log(`Generated release coordinates written to ${outputPath}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
